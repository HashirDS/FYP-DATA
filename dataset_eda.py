from wordcloud import WordCloud
from collections import Counter
import re
import nltk
from nltk.corpus import stopwords
from textstat import flesch_reading_ease, syllable_count

# --- Setup ---
nltk.download('stopwords')
stop_words = set(stopwords.words('english'))

# --- Load Dataset ---
file_path = "/content/smart_tutor_1000plus_samples.json"
with open(file_path, "r", encoding="utf-8") as f:
    data = json.load(f)

# --- Flatten into DataFrame ---
rows = []
for item in data:
    row = {
        "category": item.get("category", "unknown"),
        "subcategory": item.get("subcategory", "unknown"),
        "age_level": item.get("age_level", "unknown"),
        "user_text": "",
        "assistant_text": "",
    }
    for msg in item.get("messages", []):
        if msg["role"] == "user":
            row["user_text"] = msg["content"]
        elif msg["role"] == "assistant":
            row["assistant_text"] = msg["content"]
    rows.append(row)

df = pd.DataFrame(rows)

# --- Basic Dataset Overview ---
print("📘 Basic Dataset Info")
print("=" * 60)
print(f"Total samples: {len(df)}")
print(f"Unique Categories: {df['category'].nunique()}")
print(f"Unique Subcategories: {df['subcategory'].nunique()}")
print(f"Age Levels: {df['age_level'].unique().tolist()}\n")

print("Category Distribution:")
print(df['category'].value_counts(), "\n")

# --- Text Length Stats ---
df["user_word_count"] = df["user_text"].apply(lambda x: len(x.split()))
df["assistant_word_count"] = df["assistant_text"].apply(lambda x: len(x.split()))
df["assistant_char_count"] = df["assistant_text"].apply(len)

print("📊 Word Count Summary")
print("=" * 60)
print(df[["user_word_count", "assistant_word_count"]].describe())

# --- Token/Word Frequency Analysis ---
def clean_text(text):
    tokens = re.findall(r"\b[a-z']+\b", text.lower())
    return [t for t in tokens if t not in stop_words]

all_words = []
for txt in df["assistant_text"]:
    all_words.extend(clean_text(txt))

word_freq = Counter(all_words)
print("\n🔠 Top 20 Most Common Words:")
for w, c in word_freq.most_common(20):
    print(f"{w}: {c}")

# --- Vocabulary Richness ---
unique_words = len(set(all_words))
total_words = len(all_words)
lexical_diversity = unique_words / total_words * 100
print(f"\n🧩 Vocabulary Richness: {lexical_diversity:.2f}% unique words\n")

# --- Readability Score (Flesch Reading Ease) ---
df["readability"] = df["assistant_text"].apply(flesch_reading_ease)
print("📗 Readability (Flesch Reading Ease):")
print(df["readability"].describe())
